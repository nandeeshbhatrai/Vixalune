// Generates THIRD_PARTY_LICENSES.md: every Rust crate in the Windows build and every npm package that ends up in the front end,
// with the license each one declares. Run from the repository root: node scripts/gen-third-party.mjs
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync, existsSync } from "node:fs";

const run = (cmd, args, opts = {}) => execFileSync(cmd, args, { encoding: "utf8", maxBuffer: 64 * 1024 * 1024, ...opts });

// Rust: normal (non-dev, non-build) dependencies for the Windows target.
const tree = run("cargo", ["tree", "--manifest-path", "src-tauri/Cargo.toml", "--target", "x86_64-pc-windows-msvc", "-e", "normal", "--prefix", "none", "--format", "{p}|{l}"]);
const crates = new Map();
for (const line of tree.split(/\r?\n/)) {
  const m = /^(\S+) v(\S+)(?: \([^)]*\))?(?: \(\*\))?\|(.*)$/.exec(line.trim());
  if (!m) continue;
  if (m[1] === "vixalune") continue;
  crates.set(`${m[1]}@${m[2]}`, m[3].replace(/\s*\(\*\)\s*$/, "").trim() || "UNKNOWN");
}

// npm: production dependencies, read from node_modules.
const npmList = JSON.parse(run(process.platform === "win32" ? "npm.cmd" : "npm", ["ls", "--omit=dev", "--all", "--json"], { shell: process.platform === "win32" }));
const npm = new Map();
(function walk(deps) {
  for (const [name, info] of Object.entries(deps ?? {})) {
    if (info.version) {
      const pj = `node_modules/${name}/package.json`;
      let license = "UNKNOWN";
      if (existsSync(pj)) {
        const j = JSON.parse(readFileSync(pj, "utf8"));
        license = typeof j.license === "string" ? j.license : (j.license?.type ?? (j.licenses ? j.licenses.map((l) => l.type).join(" OR ") : "UNKNOWN"));
      }
      npm.set(`${name}@${info.version}`, license);
    }
    walk(info.dependencies);
  }
})(npmList.dependencies);

const table = (m) => [...m].sort(([a], [b]) => a.localeCompare(b)).map(([k, v]) => `| ${k} | ${v} |`).join("\n");
const out = `# Third-party licenses

Vixalune itself is MIT licensed (see LICENSE). It includes the components below. This list is generated by \`node scripts/gen-third-party.mjs\`
from the lock files as they are at build time; each entry shows the license the package *declares*. Full license texts are in each package's
source distribution. Regenerate it before every release and review any entry that is UNKNOWN, has a copyleft license (GPL/AGPL) or a license
you do not recognise.

Vixalune does **not** bundle or redistribute any of the security tools it installs (Nmap, OWASP ZAP, Semgrep, Trivy, Wireshark, Nikto). They are
downloaded by winget, apt or Docker from their publishers on the user's request, under their own licenses.

## Rust crates (Windows build, ${crates.size})

| Crate | License |
|---|---|
${table(crates)}

## npm packages (front end, ${npm.size})

| Package | License |
|---|---|
${table(npm)}
`;
writeFileSync("THIRD_PARTY_LICENSES.md", out);
console.log(`crates: ${crates.size}, npm: ${npm.size}`);
const odd = [...crates, ...npm].filter(([, l]) => /UNKNOWN|GPL|AGPL|SSPL|BUSL/i.test(l) && !/LGPL/i.test(l));
if (odd.length) console.log("REVIEW:", odd.map(([k, l]) => `${k} (${l})`).join("; "));
