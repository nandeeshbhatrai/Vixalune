import { invoke } from "@tauri-apps/api/core";
import { listen } from "@tauri-apps/api/event";
import type { Backend } from "@/domain/backend";
import type {
  ActivityEvent,
  AppInfo,
  Capabilities,
  CatalogEntry,
  InstalledTool,
  InstallPlan,
  Job,
  LabStatus,
  LaunchDefaults,
  OutputRow,
  PurgeReport,
  RunRecord,
  StorageInfo,
  Tutorial,
  UserSettings,
  PlatformReport,
  RunPreview,
  ToolQuery,
  ToolStateEntry,
  AiConversation,
  AiConversationDetail,
  AiModelList,
  AiOverview,
  AiProviderView,
  AiSendAck,
  AiSettings,
  AiStreamEvent,
  AiTestReport,
  AssistantActionOutcome,
  AssistantTurnEntry,
  DiscoveredDetails,
  DiscoverResult,
} from "@/domain/types";

/** Thin typed wrapper over Tauri IPC. No logic lives here. */
export const tauriBackend: Backend = {
  isDemo: false,
  getAppInfo: () => invoke<AppInfo>("get_app_info"),
  getCapabilities: () => invoke<Capabilities>("get_capabilities"),
  getPlatformReport: () => invoke<PlatformReport>("get_platform_report"),
  listTools: (query?: ToolQuery) => invoke<CatalogEntry[]>("list_tools", { query: query ?? null }),
  getTool: (id) => invoke<CatalogEntry>("get_tool", { id }),
  listToolStates: () => invoke<ToolStateEntry[]>("list_tool_states"),
  refreshToolStates: () => invoke<void>("refresh_tool_states"),
  listInstalledTools: () => invoke<InstalledTool[]>("list_installed_tools"),
  listJobs: () => invoke<Job[]>("list_jobs"),
  getJobOutput: (jobId) => invoke<string[]>("get_job_output", { id: jobId }),
  recentActivity: (limit) => invoke<ActivityEvent[]>("recent_activity", { limit: limit ?? null }),
  listLabs: () => invoke<LabStatus[]>("list_labs"),
  startLab: (id) => invoke<LabStatus[]>("start_lab", { id }),
  stopLab: (id) => invoke<LabStatus[]>("stop_lab", { id }),
  getLaunchDefaults: (toolId, profile) => invoke<LaunchDefaults>("get_launch_defaults", { id: toolId, profile }),
  getJob: (jobId) => invoke<Job>("get_job", { id: jobId }),
  getRunOutput: (jobId, after) => invoke<OutputRow[]>("get_run_output", { id: jobId, after }),
  listRuns: (limit) => invoke<RunRecord[]>("list_runs", { limit: limit ?? null }),
  getRun: (jobId) => invoke<RunRecord>("get_run", { id: jobId }),
  saveRunOutput: (jobId) => invoke<string | null>("save_run_output", { id: jobId }),
  openRunFolder: (jobId) => invoke<void>("open_run_folder", { id: jobId }),
  getSettings: () => invoke<UserSettings>("get_settings"),
  updateSettings: (settings) => invoke<UserSettings>("update_settings", { settings }),
  purgeHistoryNow: () => invoke<PurgeReport>("purge_history_now"),
  listTutorials: () => invoke<Tutorial[]>("list_tutorials"),
  getTutorial: (toolId) => invoke<Tutorial>("get_tutorial", { id: toolId }),
  openTutorialLink: (toolId, index) => invoke<void>("open_tutorial_link", { toolId, index }),
  getInstallPlan: (toolId) => invoke<InstallPlan>("get_install_plan", { id: toolId }),
  installTool: (id, allowElevation) => invoke<string>("install_tool", { id, allowElevation }),
  uninstallTool: (id, allowElevation) => invoke<string>("uninstall_tool", { id, allowElevation }),
  verifyTool: (id) => invoke<string>("verify_tool", { id }),
  previewLaunch: (id, profile, values, approvals) => invoke<RunPreview>("preview_launch", { id, profile, values, approvals }),
  launchTool: (id, profile, values, approvals) => invoke<string>("launch_tool", { id, profile, values, approvals }),
  runSetupAction: (id, confirmed) => invoke<string>("run_setup_action", { id, confirmed }),
  requestRestart: (confirmed, delaySecs) => invoke<void>("request_restart", { confirmed, delaySecs }),
  cancelRestart: () => invoke<void>("cancel_restart"),
  openSetupLink: (id) => invoke<void>("open_setup_link", { id }),
  approveJob: (jobId) => invoke<void>("approve_job", { id: jobId }),
  cancelJob: (jobId) => invoke<void>("cancel_job", { id: jobId }),
  getStorageInfo: () => invoke<StorageInfo>("get_storage_info"),
  updateStorage: (update) => invoke<StorageInfo>("update_storage", { update }),
  openReleasePage: () => invoke<void>("open_release_page"),
  openLink: (toolId, kind) => invoke<void>("open_link", { toolId, kind }),
  aiOverview: () => invoke<AiOverview>("ai_overview"),
  aiSaveCredential: (provider, apiKey, label) => invoke<AiProviderView>("ai_save_credential", { provider, apiKey, label }),
  aiDeleteCredential: (provider) => invoke<AiProviderView>("ai_delete_credential", { provider }),
  aiUpdateConfig: (config) => invoke<AiProviderView>("ai_update_config", { config }),
  aiSetActive: (provider) => invoke<AiProviderView>("ai_set_active", { provider }),
  aiUpdateSettings: (settings) => invoke<AiSettings>("ai_update_settings", { settings }),
  aiListModels: (provider) => invoke<AiModelList>("ai_list_models", { provider }),
  aiTestConnection: (provider, model) => invoke<AiTestReport>("ai_test_connection", { provider, model }),
  aiCreateConversation: (provider, model) => invoke<AiConversation>("ai_create_conversation", { provider, model }),
  aiListConversations: () => invoke<AiConversation[]>("ai_list_conversations"),
  aiGetConversation: (id) => invoke<AiConversationDetail>("ai_get_conversation", { id }),
  aiDeleteConversation: (id) => invoke<void>("ai_delete_conversation", { id }),
  aiDeleteAllConversations: () => invoke<number>("ai_delete_all_conversations"),
  aiSendMessage: (input) => invoke<AiSendAck>("ai_send_message", { input }),
  aiRetry: (conversationId, provider, model) => invoke<AiSendAck>("ai_retry", { conversationId, provider, model }),
  aiCancel: (requestId) => invoke<void>("ai_cancel", { requestId }),
  aiOpenProviderPage: (provider, page) => invoke<void>("ai_open_provider_page", { provider, page }),
  discoverSearch: (query) => invoke<DiscoverResult[]>("discover_search", { query }),
  discoverDetails: (id) => invoke<DiscoveredDetails>("discover_details", { id }),
  discoverAdd: (id) => invoke<CatalogEntry>("discover_add", { id }),
  communityRemove: (id) => invoke<void>("community_remove", { id }),
  assistantAsk: (input) => invoke<AiSendAck>("assistant_ask", { input }),
  assistantRetry: (conversationId, provider, model) => invoke<AiSendAck>("assistant_retry", { conversationId, provider, model }),
  assistantExplainRun: (conversationId, runId, consent, provider, model) => invoke<AiSendAck>("assistant_explain_run", { conversationId, runId, consent, provider, model }),
  assistantTurns: (conversationId) => invoke<AssistantTurnEntry[]>("assistant_turns", { conversationId }),
  assistantRunAction: (action) => invoke<AssistantActionOutcome>("assistant_run_action", { action }),
  assistantOpenEvidence: (conversationId, messageId, evidenceId) => invoke<void>("assistant_open_evidence", { conversationId, messageId, evidenceId }),
  onAiEvent: async (handler) => {
    const unlisten = await listen<AiStreamEvent>("ai-stream", (e) => handler(e.payload));
    return unlisten;
  },
};


